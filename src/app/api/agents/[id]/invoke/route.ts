import { NextResponse } from "next/server";
import { db } from "@/lib/firebase";
import { doc, getDoc, collection, addDoc } from "firebase/firestore";
import { mockAgents } from "@/data/mock";
import { getModel } from "@/lib/ai";
import { SchemaType } from "@google/generative-ai";
import {
  checkRateLimit,
  getClientIp,
  inspectAndRedactPrompt,
  isSafeHttpUrl,
  sanitizePlainText,
} from "@/lib/security";
import type { Agent, AgentExecutionLog, AutonomyLevel, ExecutionStatus } from "@/types";
import { AutonomyLevelValues } from "@/types";

const executionResponseSchema = {
  type: SchemaType.OBJECT,
  properties: {
    summary: {
      type: SchemaType.STRING,
      description: "Concise executive summary of what the agent analyzed or accomplished.",
    },
    reasoningSteps: {
      type: SchemaType.ARRAY,
      items: { type: SchemaType.STRING },
      description: "3 to 5 clear reasoning or execution steps taken by the autonomous agent.",
    },
    proposedActions: {
      type: SchemaType.ARRAY,
      items: {
        type: SchemaType.OBJECT,
        properties: {
          tool: {
            type: SchemaType.STRING,
            description: "Tool or integration invoked (e.g. 'Salesforce CRM', 'GitHub API', 'SQL Analytics', 'Slack Webhook').",
          },
          operation: {
            type: SchemaType.STRING,
            description: "Specific operation (e.g. 'read_metrics', 'draft_response', 'issue_refund', 'update_record').",
          },
          riskLevel: {
            type: SchemaType.STRING,
            description: "Must be 'low', 'medium', or 'high'. State-changing writes/payments are 'high'.",
          },
          payloadPreview: {
            type: SchemaType.STRING,
            description: "Compact JSON or summary of parameters passed to the tool.",
          },
        },
        required: ["tool", "operation", "riskLevel", "payloadPreview"],
      },
    },
    deliverable: {
      type: SchemaType.STRING,
      description: "The final detailed output, report, code, or response generated by the agent for the user.",
    },
  },
  required: ["summary", "reasoningSteps", "proposedActions", "deliverable"],
};

export async function POST(
  req: Request,
  context: { params: Promise<{ id: string }> }
) {
  const startTime = Date.now();

  try {
    const { id: rawAgentId } = await context.params;
    const agentId = rawAgentId?.trim() || "";

    if (!agentId || !/^[a-zA-Z0-9_-]{1,128}$/.test(agentId)) {
      return NextResponse.json({ error: "Invalid agent identifier." }, { status: 400 });
    }

    // 1. Rate Limit Check (20 sandbox invocations per minute per IP)
    const clientIp = getClientIp(req);
    const rateLimit = checkRateLimit(`invoke:${clientIp}`, 20, 60_000);
    if (!rateLimit.allowed) {
      return NextResponse.json(
        {
          error: `Sandbox rate limit exceeded. Try again in ${rateLimit.resetInSeconds}s.`,
        },
        { status: 429 }
      );
    }

    const body = await req.json().catch(() => ({}));
    const rawPrompt = typeof body.taskPrompt === "string" ? body.taskPrompt.trim() : "";
    const piiRedactionEnabled = body.piiRedactionEnabled !== false;
    const userId =
      typeof body.userId === "string" && body.userId.trim()
        ? sanitizePlainText(body.userId, 128)
        : "sandbox-guest";

    if (!rawPrompt || rawPrompt.length < 3) {
      return NextResponse.json(
        { error: "Please provide a task prompt (at least 3 characters) to invoke the agent." },
        { status: 400 }
      );
    }

    // 2. Lookup Agent in Firestore or fallback to mockAgents
    let agent: Agent | undefined;
    try {
      const snap = await getDoc(doc(db, "agents", agentId));
      if (snap.exists()) {
        agent = { id: snap.id, ...snap.data() } as Agent;
      }
    } catch {
      // Fallback to mockAgents below
    }

    if (!agent) {
      agent = mockAgents.find(
        (a) => a.id === agentId || a.id === agentId.replace(/^agent-/, "")
      );
    }

    if (!agent) {
      return NextResponse.json({ error: "Agent not found." }, { status: 404 });
    }

    const requestedAutonomy = body.autonomyPolicy as AutonomyLevel | undefined;
    const autonomyPolicy: AutonomyLevel =
      requestedAutonomy && AutonomyLevelValues.includes(requestedAutonomy)
        ? requestedAutonomy
        : agent.autonomyLevel || "Assisted Decision-Making";

    // 3. Run AgentVerse Control Plane (ACP) DLP & Security Guardrail Firewall
    const guardrail = inspectAndRedactPrompt(rawPrompt, piiRedactionEnabled);

    // If Prompt Injection / Jailbreak is detected, block immediately before hitting the agent
    if (!guardrail.passed) {
      const blockedLog: AgentExecutionLog = {
        id: `exec-${Date.now()}`,
        agentId: agent.id,
        agentName: agent.name,
        developer: agent.developer,
        userId,
        taskPrompt: sanitizePlainText(rawPrompt, 1000),
        sanitizedPrompt: guardrail.sanitizedPrompt,
        autonomyPolicy,
        piiRedactionEnabled,
        status: "blocked_guardrail",
        guardrail,
        latencyMs: Date.now() - startTime,
        estimatedTokens: 0,
        costUsd: 0,
        createdAt: new Date().toISOString(),
      };

      await addDoc(collection(db, "agentExecutions"), blockedLog).catch(() => {});

      return NextResponse.json({
        execution: blockedLog,
        message: "Blocked by AgentVerse AI Firewall: Prompt Injection attempt prevented.",
      });
    }

    // 4. Execute Agent via Gemini Runtime with Structured Envelope
    const systemInstruction = `You are "${agent.name}", a specialized autonomous AI agent listed on the AgentVerse Marketplace, developed by "${agent.developer}".
Primary Function: ${agent.primaryFunction || agent.shortDescription || "Autonomous Task Execution"}
Capabilities: ${(agent.capabilities || []).join(", ")}
Tech Stack & Integrations: ${[...(agent.techStack || []), ...(agent.integrations || [])].join(", ")}
System Persona / Instructions: ${agent.systemPrompt || agent.description}
Enforced Autonomy Policy: ${autonomyPolicy}

Execute the user's task professionally and authentically as ${agent.name}.
Produce realistic reasoningSteps, proposedActions (listing which tools/APIs you call and their riskLevel: 'low', 'medium', or 'high'), and a comprehensive, high-value deliverable.`;

    const modelNames = ["gemini-2.5-flash", "gemini-2.5-pro", "gemini-flash-latest"];
    let parsedOutput: NonNullable<AgentExecutionLog["output"]> | null = null;

    // 4a. If the provider configured an external remote webhook URL, proxy the sanitized payload first
    if (agent.endpointUrl && isSafeHttpUrl(agent.endpointUrl)) {
      try {
        const controller = new AbortController();
        const timeout = setTimeout(() => controller.abort(), 6000);
        const webhookRes = await fetch(agent.endpointUrl, {
          method: "POST",
          headers: {
            "Content-Type": "application/json",
            "X-AgentVerse-Control-Plane": "v1",
            "X-AgentVerse-Agent-Id": agent.id,
            "X-AgentVerse-Autonomy-Policy": autonomyPolicy,
          },
          body: JSON.stringify({
            agentId: agent.id,
            sanitizedPrompt: guardrail.sanitizedPrompt,
            autonomyPolicy,
            piiRedactedCount: guardrail.piiRedactedCount,
          }),
          signal: controller.signal,
        });
        clearTimeout(timeout);

        if (webhookRes.ok) {
          const remoteJson = await webhookRes.json();
          if (remoteJson && (remoteJson.deliverable || remoteJson.summary || remoteJson.output)) {
            parsedOutput = {
              summary: String(
                remoteJson.summary ||
                  `Remote webhook (${agent.endpointUrl}) executed task for ${agent.name}.`
              ),
              reasoningSteps: Array.isArray(remoteJson.reasoningSteps)
                ? remoteJson.reasoningSteps
                : ["Forwarded sanitized payload to external provider webhook.", "Received structured response from remote agent endpoint."],
              proposedActions: Array.isArray(remoteJson.proposedActions)
                ? remoteJson.proposedActions
                : [
                    {
                      tool: "External Provider Webhook",
                      operation: "POST " + agent.endpointUrl,
                      riskLevel: guardrail.highRiskActionDetected ? "high" : "low",
                      payloadPreview: JSON.stringify({ status: webhookRes.status }),
                    },
                  ],
              deliverable: String(remoteJson.deliverable || remoteJson.output || JSON.stringify(remoteJson)),
            };
          }
        }
      } catch (webhookErr) {
        console.warn(`External agent webhook (${agent.endpointUrl}) unreachable, falling back to hosted Gemini runtime:`, webhookErr);
      }
    }

    // 4b. Hosted AgentVerse Runtime (Gemini 2.5 Flash / Pro hydrated with the agent's persona & tool specs)
    if (!parsedOutput) {
      for (const modelName of modelNames) {
        try {
          const model = getModel({
            model: modelName,
            systemInstruction,
            generationConfig: {
              responseMimeType: "application/json",
              responseSchema: executionResponseSchema,
            },
          });

          const result = await model.generateContent(
            `Execute the following sanitized client task:\n\n"${guardrail.sanitizedPrompt}"`
          );
          const text = result.response.text();
          const json = JSON.parse(text);
          if (json && json.summary && json.deliverable) {
            parsedOutput = {
              summary: json.summary,
              reasoningSteps: Array.isArray(json.reasoningSteps) ? json.reasoningSteps : [],
              proposedActions: Array.isArray(json.proposedActions)
                ? json.proposedActions.map((act: any) => ({
                    tool: String(act.tool || "AgentCore"),
                    operation: String(act.operation || "execute"),
                    riskLevel:
                      act.riskLevel === "high" || act.riskLevel === "medium"
                        ? act.riskLevel
                        : "low",
                    payloadPreview: String(act.payloadPreview || "{}"),
                  }))
                : [],
              deliverable: json.deliverable,
            };
            break;
          }
        } catch (err) {
          console.warn(`Agent runtime model ${modelName} failed, trying fallback:`, err);
        }
      }
    }

    // Deterministic fallback if Gemini API quota/network is unavailable
    if (!parsedOutput) {
      parsedOutput = {
        summary: `${agent.name} processed your request under "${autonomyPolicy}" governance.`,
        reasoningSteps: [
          `Validated input schema and verified DLP sanitization (${guardrail.piiRedactedCount} PII token(s) masked).`,
          `Loaded ${agent.name} domain context (${(agent.capabilities || []).slice(0, 3).join(", ")}).`,
          `Synthesized actionable recommendations and prepared tool invocation payload.`,
        ],
        proposedActions: [
          {
            tool: agent.integrations?.[0] || "AgentVerse Workspace API",
            operation: guardrail.highRiskActionDetected ? "execute_privileged_action" : "generate_analysis_report",
            riskLevel: guardrail.highRiskActionDetected ? "high" : "low",
            payloadPreview: JSON.stringify({
              agent: agent.id,
              autonomy: autonomyPolicy,
              redactedTokens: guardrail.piiRedactedCount,
            }),
          },
        ],
        deliverable: `### ${agent.name} Execution Output\n\n**Task Analyzed:** ${guardrail.sanitizedPrompt}\n\n1. **Primary Assessment:** Based on ${agent.primaryFunction || "configured capabilities"}, the optimal workflow has been structured.\n2. **Recommended Next Steps:** Review the structured tool calls above and approve any state-changing operations in your AgentVerse Control Plane.`,
      };
    }

    // 5. Enforce Human-in-the-Loop (HITL) Governance Policy
    const hasHighRiskToolCall =
      guardrail.highRiskActionDetected ||
      parsedOutput.proposedActions.some((a) => a.riskLevel === "high");

    const requiresHumanApproval =
      hasHighRiskToolCall && autonomyPolicy !== "Fully Autonomous Operation";

    const finalStatus: ExecutionStatus = requiresHumanApproval
      ? "pending_approval"
      : "completed";

    const latencyMs = Date.now() - startTime;
    const estimatedTokens = Math.max(
      120,
      Math.round((guardrail.sanitizedPrompt.length + parsedOutput.deliverable.length) / 3.5)
    );
    const costUsd = Number((estimatedTokens * 0.000015).toFixed(4));

    const executionLog: AgentExecutionLog = {
      id: `exec-${Date.now()}`,
      agentId: agent.id,
      agentName: agent.name,
      developer: agent.developer,
      userId,
      taskPrompt: sanitizePlainText(rawPrompt, 1000),
      sanitizedPrompt: guardrail.sanitizedPrompt,
      autonomyPolicy,
      piiRedactionEnabled,
      status: finalStatus,
      guardrail,
      output: parsedOutput,
      latencyMs,
      estimatedTokens,
      costUsd,
      createdAt: new Date().toISOString(),
    };

    try {
      const docRef = await addDoc(collection(db, "agentExecutions"), executionLog);
      executionLog.id = docRef.id;
    } catch {
      // Keep generated id if Firestore write is offline
    }

    return NextResponse.json({
      execution: executionLog,
    });
  } catch (error: any) {
    console.error("Agent invocation error:", error);
    return NextResponse.json(
      { error: "Agent runtime encountered an unexpected error." },
      { status: 500 }
    );
  }
}
